import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const projectRoot = resolve(__dirname, '..');
const logoDir = resolve(projectRoot, 'public/files/logo');
const outputFile = resolve(projectRoot, 'src/data/logoManifest.ts');

const allowedExt = new Set(['.svg', '.png', '.jpg', '.jpeg', '.webp']);

if (!existsSync(logoDir)) {
  throw new Error(`Logo directory not found: ${logoDir}`);
}

const logoFilenames = readdirSync(logoDir, { withFileTypes: true })
  .filter((entry) => entry.isFile())
  .map((entry) => entry.name)
  .filter((name) => allowedExt.has(extname(name).toLowerCase()))
  .sort((a, b) => a.localeCompare(b));

const fileContent = `// Auto-generated by scripts/generate-logo-manifest.mjs. Do not edit manually.\nexport const logoFilenames = ${JSON.stringify(logoFilenames, null, 2)} as const;\n\nexport const logoUrls = logoFilenames.map((name) => \`/files/logo/\${name}\`);\n`;

writeFileSync(outputFile, fileContent, 'utf8');
console.log(`Generated ${outputFile} with ${logoFilenames.length} logos.`);
